// Builds results/ANALYSIS.md from the raw result files in results/ (no model is run, nothing is estimated).
// Usage: node scripts/analyse_results.js
// make_data_md.js copies results/ANALYSIS.md into DATA.md.
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const RES = path.join(ROOT, "results");

// --- helpers -------------------------------------------------------------
function parseCsv(text) {
  const rows = []; let row = [], f = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) { if (ch === '"' && text[i + 1] === '"') { f += '"'; i++; } else if (ch === '"') q = false; else f += ch; }
    else if (ch === '"') q = true;
    else if (ch === ",") { row.push(f); f = ""; }
    else if (ch === "\n") { row.push(f); rows.push(row); row = []; f = ""; }
    else if (ch !== "\r") f += ch;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  const [head, ...data] = rows.filter(r => r.length > 1);
  return data.map(r => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ""])));
}
// same idea as convo/structured.normalise: compare words only, ignoring spaces and punctuation
const norm = s => (s || "").replace(/[\s\p{P}\p{S}]/gu, "").toLowerCase();
const load = f => JSON.parse(fs.readFileSync(path.join(RES, f), "utf8"));
const pct = (a, b) => (b ? Math.round((100 * a) / b) : 0);
const frac = (a, b) => `${a}/${b}`;
const isChinese = s => /[一-鿿]{4,}/.test(s || "");
const isEnglish = s => !isChinese(s) && /[a-z]{3,}/i.test(s || "");

// --- load ----------------------------------------------------------------
const key = Object.fromEntries(parseCsv(fs.readFileSync(path.join(ROOT, "data", "test_cases.csv"), "utf8"))
  .map(c => [c.id, c.correct.split("|").map(norm).filter(Boolean)]));
const files = fs.readdirSync(RES).filter(f => f.endsWith(".json")).sort();
const firstRun = (kind, split) => {
  const out = {};
  for (const f of files) {
    if (!f.includes(`_${kind}_`) || !f.endsWith(`_${split}.json`)) continue;
    const d = load(f);
    if (!out[d.prompt_version]) out[d.prompt_version] = { file: f, data: d };
  }
  return out;
};
const tune = firstRun("corrections", "tune");
const test = firstRun("corrections", "test");
const conv = firstRun("conversation", "na");
const versions = Object.keys(tune).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));

// Re-score every run with the CURRENT answer key so versions are compared fairly.
function score(rows) {
  const out = rows.map(r => {
    const right = r.has_mistake ? r.flagged && key[r.id].includes(norm(r.model_fix)) : !r.flagged;
    return { ...r, right };
  });
  const m = out.filter(r => r.has_mistake), ok = out.filter(r => !r.has_mistake), fl = out.filter(r => r.flagged);
  return {
    rows: out,
    caught: m.filter(r => r.flagged).length, matching: m.filter(r => r.right).length, nm: m.length,
    falseFix: ok.filter(r => r.flagged).length, nok: ok.length,
    flagged: fl.length, english: fl.filter(r => isEnglish(r.explanation_model)).length,
    chinese: fl.filter(r => isChinese(r.explanation_model)).length,
  };
}
const S = Object.fromEntries(versions.map(v => [v, score(tune[v].data.rows)]));
const best = versions.reduce((b, v) => {
  const s = S[v], t = S[b];
  return s.matching - s.falseFix > t.matching - t.falseFix ? v : b;
}, versions[0]);

// --- write ---------------------------------------------------------------
const L = [];
L.push(`*Generated by \`scripts/analyse_results.js\` from the raw result files in \`results/\`. Every number below is computed from those files; nothing is estimated. All runs are re-scored with the current answer key (see "Answer-key changes"), so versions are compared on equal terms.*`);
L.push("");

// 1. headline
const b = S[best], v1 = S[versions[0]];
L.push("### 1. Headline (tune sentences)");
L.push("");
L.push(`| | Baseline (never corrects) | ${versions[0]} (first prompt) | ${best} (best version) |`);
L.push("|---|---|---|---|");
L.push(`| Mistakes caught | 0/${b.nm} | ${frac(v1.caught, v1.nm)} | **${frac(b.caught, b.nm)}** |`);
L.push(`| Corrections matching our answer | 0/${b.nm} | ${frac(v1.matching, v1.nm)} (${pct(v1.matching, v1.nm)}%) | **${frac(b.matching, b.nm)} (${pct(b.matching, b.nm)}%)** |`);
L.push(`| Correct sentences wrongly "fixed" | 0/${b.nok} | ${frac(v1.falseFix, v1.nok)} | **${frac(b.falseFix, b.nok)}** |`);
L.push(`| Sentences handled right overall | ${b.nok}/${b.nm + b.nok} | ${v1.matching + v1.nok - v1.falseFix}/${v1.nm + v1.nok} | **${b.matching + b.nok - b.falseFix}/${b.nm + b.nok}** |`);
L.push("");
L.push(`The baseline gets the ${b.nok} correct sentences "right" by never doing anything, but it helps a learner with none of the ${b.nm} mistakes. ${best} fixes ${b.matching} of them correctly.`);
L.push("");

// 2. charts
L.push("### 2. Progress by version");
L.push("");
// text bar charts: render the same everywhere (GitHub cuts off mermaid charts)
const bar = p => "█".repeat(Math.round(p / 10)) + "░".repeat(10 - Math.round(p / 10));
L.push("| Version | Corrections matching our answer (higher is better) | Correct sentences wrongly fixed (lower is better) |");
L.push("|---|---|---|");
L.push(`| Baseline | \`${bar(0)}\` 0% | \`${bar(0)}\` 0% |`);
for (const v of versions) {
  const m = pct(S[v].matching, S[v].nm), f = pct(S[v].falseFix, S[v].nok);
  L.push(`| ${v === best ? "**" + v + "**" : v} | \`${bar(m)}\` ${m}% | \`${bar(f)}\` ${f}% |`);
}
L.push("");
L.push("| Version | Caught | Matching | Wrongly fixed | Gap: caught but fixed wrongly |");
L.push("|---|---|---|---|---|");
for (const v of versions) { const s = S[v]; L.push(`| ${v} | ${frac(s.caught, s.nm)} | ${frac(s.matching, s.nm)} | ${frac(s.falseFix, s.nok)} | ${s.caught - s.matching} |`); }
L.push("");
L.push(`**Catching vs fixing.** The last column counts mistakes the model noticed but fixed wrongly. On the tune sentences it stays small (${Math.min(...versions.map(v => S[v].caught - S[v].matching))} to ${Math.max(...versions.map(v => S[v].caught - S[v].matching))}), so the real swings came from missed mistakes and from over-correcting. On unseen sentences the gap was much bigger (section 5).`);
L.push("");
L.push(`Note: because every run is re-scored with the current answer key, v1 shows ${frac(v1.matching, v1.nm)} matching here, not the 4/7 recorded at the time. We later accepted 你们有茶吗？ as a second right answer, which v1 had given.`);
L.push("");

// 3. sentence grid
L.push("### 3. Sentence by sentence (✅ = right, ❌ = wrong)");
L.push("");
L.push(`A sentence with a mistake is right if the fix matches one of our answers. A correct sentence is right if it is left unchanged.`);
L.push("");
L.push(`| ID | Learner sentence | Type | ${versions.join(" | ")} | Versions right |`);
L.push(`|---|---|---|${versions.map(() => "---").join("|")}|---|`);
const ids = tune[versions[0]].data.rows.map(r => r.id);
const hard = [];
for (const id of ids) {
  const r0 = S[versions[0]].rows.find(r => r.id === id);
  const marks = versions.map(v => S[v].rows.find(r => r.id === id).right);
  const n = marks.filter(Boolean).length;
  if (n <= versions.length / 2) hard.push(`${r0.learner} (${n}/${versions.length})`);
  L.push(`| ${id} | ${r0.learner} | ${r0.has_mistake ? r0.category_expected : "correct"} | ${marks.map(m => (m ? "✅" : "❌")).join(" | ")} | ${n}/${versions.length} |`);
}
L.push("");
L.push(`**Hardest sentences** (right in half the versions or fewer): ${hard.join("; ") || "none"}.`);
L.push("");

// 4. explanations
L.push("### 4. Explanation language (flagged sentences)");
L.push("");
L.push("We ask for explanations in English, because an A2 learner can't read a Chinese grammar explanation. Language is detected automatically (4+ Chinese characters in a row = Chinese), so treat it as approximate.");
L.push("");
L.push("| Version | Flagged | English | Chinese |");
L.push("|---|---|---|---|");
for (const v of versions) { const s = S[v]; L.push(`| ${v} | ${s.flagged} | ${s.english} (${pct(s.english, s.flagged)}%) | ${s.chinese} |`); }
L.push("");
L.push("English explanations only appeared once the prompt included worked examples written in English (v4). This is still our weakest area.");
L.push("");

// 5. early test-split run
for (const v of Object.keys(test)) {
  const d = test[v].data, s = score(d.rows);
  L.push(`### 5. Early test-split run (${v}, 32 unseen sentences)`);
  L.push("");
  L.push(`This was run once by accident with ${v} (see "Test-split runs"). It was not used to choose any change, but it shows how ${v} behaved on sentences it had never seen.`);
  L.push("");
  L.push(`| | Baseline | ${v} |`);
  L.push("|---|---|---|");
  L.push(`| Mistakes caught | 0/${s.nm} | ${frac(s.caught, s.nm)} (${pct(s.caught, s.nm)}%) |`);
  L.push(`| Corrections matching our answer | 0/${s.nm} | ${frac(s.matching, s.nm)} (${pct(s.matching, s.nm)}%) |`);
  L.push(`| Correct sentences wrongly "fixed" | 0/${s.nok} | ${frac(s.falseFix, s.nok)} (${pct(s.falseFix, s.nok)}%) |`);
  L.push("");
  const cats = {};
  for (const r of s.rows.filter(r => r.has_mistake)) {
    const c = (cats[r.category_expected] ||= { n: 0, caught: 0, right: 0 });
    c.n++; c.caught += r.flagged ? 1 : 0; c.right += r.right ? 1 : 0;
  }
  L.push("| Mistake type | Sentences | Caught | Fixed right |");
  L.push("|---|---|---|---|");
  for (const [c, x] of Object.entries(cats).sort((a, b) => b[1].n - a[1].n)) L.push(`| ${c} | ${x.n} | ${x.caught} | ${x.right} |`);
  L.push("");
  L.push(`${v} noticed almost every mistake but fixed very few correctly, the same "catching vs fixing" gap as on the tune sentences, only bigger. This is why later versions focused on the quality of the fix and on not over-correcting. The final test run will show how much of the tune-split improvement carries over to unseen sentences.`);
  L.push("");
}

// 6. reproducibility + conversations
L.push("### 6. Reliability checks");
L.push("");
const v1tune = files.filter(f => f.includes("_corrections_") && f.includes("_v1_tune"));
if (v1tune.length > 1) {
  const [a, c] = v1tune.map(f => load(f).rows);
  const same = a.every((r, i) => r.model_fix === c[i].model_fix && r.flagged === c[i].flagged && r.explanation_model === c[i].explanation_model);
  L.push(`- **Repeatable:** v1 was run twice on the tune sentences. The two runs were ${same ? "identical on every sentence" : "NOT identical"} (temperature 0), so differences between versions come from our changes, not chance.`);
}
const convVs = Object.keys(conv).sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));
const cm = convVs.map(v => conv[v].data.metrics);
const allPerfect = cm.every(m => m.character_consistency === 1 && m.context_retention === 1);
L.push(`- **Conversation:** across ${convVs.length} versions, the waiter stayed in character in ${cm.map(m => Math.round(m.character_consistency * m.n_waiter_turns) + "/" + m.n_waiter_turns).join(", ")} turns and remembered the order in ${cm.map(m => Math.round(m.context_retention * m.n_scripts) + "/" + m.n_scripts).join(", ")} chats${allPerfect ? " (perfect every time)" : ""}. The waiter prompt never changed; only the mistake checker did.`);
L.push(`- **Valid output:** every run produced a readable answer for every sentence (${versions.map(v => tune[v].data.metrics.valid_output_rate === 1 ? "100%" : Math.round(tune[v].data.metrics.valid_output_rate * 100) + "%").join(", ")}).`);
L.push("");

// 7. caveats
L.push("### 7. Caveats");
L.push("");
L.push(`- The tune split is only ${b.nm + b.nok} sentences, so one sentence moves a score by ${pct(1, b.nm)} to ${pct(1, b.nok)} points. The final test on 32 unseen sentences is the real measure.`);
L.push(`- "Matching our answer" is strict: a correct fix worded differently counts as wrong. A person should also check the corrections by hand.`);
L.push(`- We picked ${best} as best because it has the most matching fixes minus wrong "fixes" on the tune split.`);

fs.writeFileSync(path.join(RES, "ANALYSIS.md"), L.join("\n") + "\n");
console.log("best", best, versions.map(v => `${v}:${S[v].caught}/${S[v].matching}/${S[v].falseFix}`).join(" "));
